-- Harden the pre-existing profile setup used when Auth creates a user.
-- The function uses fully qualified object names and cannot be called directly
-- by website visitors or signed-in users.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email);
  return new;
end;
$$;

revoke execute on function public.handle_new_user() from public, anon, authenticated;
grant execute on function public.handle_new_user() to service_role;

drop policy if exists "Users can view own profile" on public.profiles;
create policy "Users can view own profile" on public.profiles
for select to authenticated
using ((select auth.uid()) = id);

-- Public before-and-after gallery. Patient names, initials, medical record
-- numbers, dates of birth, diagnoses, release documents, and medical notes do
-- not belong in this table.
create table if not exists public.gallery_items (
  id uuid primary key default gen_random_uuid(),
  case_number bigint generated always as identity unique,
  service text not null check (
    service in (
      'Botox & Neurotoxins',
      'Dermal Fillers',
      'Skin Treatments',
      'Wellness Progress',
      'Other Treatment'
    )
  ),
  before_url text not null check (char_length(before_url) between 10 and 2000),
  after_url text not null check (char_length(after_url) between 10 and 2000),
  before_path text not null check (char_length(before_path) between 5 and 500),
  after_path text not null check (char_length(after_path) between 5 and 500),
  authorization_confirmed boolean not null default false,
  privacy_checked boolean not null default false,
  authorization_verified_at timestamptz,
  authorization_verified_by uuid references auth.users(id) on delete restrict,
  published boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint gallery_requires_authorization_before_storage check (
    authorization_confirmed = true
    and privacy_checked = true
    and authorization_verified_at is not null
    and authorization_verified_by is not null
  ),
  constraint published_gallery_requires_authorization check (
    not published
    or (
      authorization_confirmed = true
      and privacy_checked = true
      and authorization_verified_at is not null
      and authorization_verified_by is not null
    )
  )
);

create index if not exists gallery_items_public_order_idx
on public.gallery_items (sort_order, case_number desc)
where published = true and authorization_confirmed = true and privacy_checked = true;

create index if not exists gallery_items_authorization_verified_by_idx
on public.gallery_items (authorization_verified_by);

alter table public.gallery_items enable row level security;

revoke all on table public.gallery_items from anon, authenticated;
revoke all on sequence public.gallery_items_case_number_seq from anon, authenticated;
grant select on public.gallery_items to anon, authenticated;
grant insert, update, delete on public.gallery_items to authenticated;
grant usage, select on sequence public.gallery_items_case_number_seq to authenticated;

create policy "Visitors can read approved gallery items" on public.gallery_items
for select to anon
using (published and authorization_confirmed and privacy_checked and authorization_verified_at is not null);

create policy "Signed-in users can read allowed gallery items" on public.gallery_items
for select to authenticated
using (
  (published and authorization_confirmed and privacy_checked and authorization_verified_at is not null)
  or exists (
    select 1 from public.site_admins
    where site_admins.user_id = (select auth.uid())
  )
);

create policy "Site admins can add gallery items" on public.gallery_items
for insert to authenticated
with check (
  authorization_confirmed
  and privacy_checked
  and authorization_verified_at is not null
  and authorization_verified_by = (select auth.uid())
  and exists (
    select 1 from public.site_admins
    where site_admins.user_id = (select auth.uid())
  )
);

create policy "Site admins can update gallery items" on public.gallery_items
for update to authenticated
using (
  exists (
    select 1 from public.site_admins
    where site_admins.user_id = (select auth.uid())
  )
)
with check (
  authorization_confirmed
  and privacy_checked
  and authorization_verified_at is not null
  and authorization_verified_by is not null
  and exists (
    select 1 from public.site_admins
    where site_admins.user_id = (select auth.uid())
  )
);

create policy "Site admins can delete gallery items" on public.gallery_items
for delete to authenticated
using (
  exists (
    select 1 from public.site_admins
    where site_admins.user_id = (select auth.uid())
  )
);
