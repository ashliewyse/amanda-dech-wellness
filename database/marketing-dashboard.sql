-- Marketing-only website manager schema.
-- Do not store patient, appointment, billing, intake, or medical-record data here.

create table if not exists public.site_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.site_content (
  id text primary key,
  content jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null,
  constraint site_content_main_row check (id = 'main')
);

create table if not exists public.testimonials (
  id bigint generated by default as identity primary key,
  quote text not null check (char_length(quote) between 10 and 500),
  display_name text not null check (char_length(display_name) between 1 and 80),
  source text not null default 'Website testimonial',
  permission_confirmed boolean not null default false,
  published boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint published_testimonial_requires_permission check (not published or permission_confirmed)
);

create index if not exists site_content_updated_by_idx
on public.site_content (updated_by);

alter table public.site_admins enable row level security;
alter table public.site_content enable row level security;
alter table public.testimonials enable row level security;

grant usage on schema public to anon, authenticated;
revoke all on table public.site_admins from anon, authenticated;
revoke all on table public.site_content from anon, authenticated;
revoke all on table public.testimonials from anon, authenticated;
revoke all on sequence public.testimonials_id_seq from anon, authenticated;

grant select on public.site_admins to authenticated;
grant select on public.site_content to anon, authenticated;
grant update on public.site_content to authenticated;
grant select on public.testimonials to anon, authenticated;
grant insert, update, delete on public.testimonials to authenticated;
grant usage, select on sequence public.testimonials_id_seq to authenticated;

create policy "Site admins can view their own membership" on public.site_admins
for select to authenticated using ((select auth.uid()) = user_id);

create policy "Public can read website content" on public.site_content
for select to anon, authenticated using (true);

create policy "Site admins can update website content" on public.site_content
for update to authenticated
using (exists (select 1 from public.site_admins where site_admins.user_id = (select auth.uid())))
with check (id = 'main' and exists (select 1 from public.site_admins where site_admins.user_id = (select auth.uid())));

create policy "Visitors can read approved testimonials" on public.testimonials
for select to anon
using (published = true and permission_confirmed = true);

create policy "Signed-in users can read allowed testimonials" on public.testimonials
for select to authenticated
using (
  (published = true and permission_confirmed = true)
  or exists (
    select 1 from public.site_admins
    where site_admins.user_id = (select auth.uid())
  )
);

create policy "Site admins can add testimonials" on public.testimonials
for insert to authenticated
with check (exists (select 1 from public.site_admins where site_admins.user_id = (select auth.uid())));

create policy "Site admins can update testimonials" on public.testimonials
for update to authenticated
using (exists (select 1 from public.site_admins where site_admins.user_id = (select auth.uid())))
with check (exists (select 1 from public.site_admins where site_admins.user_id = (select auth.uid())));

create policy "Site admins can delete testimonials" on public.testimonials
for delete to authenticated
using (exists (select 1 from public.site_admins where site_admins.user_id = (select auth.uid())));

